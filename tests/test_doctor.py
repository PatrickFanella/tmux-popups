"""Ordinary diagnosis is read-only; input checks require explicit invocation."""
import os
import shlex
import subprocess
import unittest
import test_bindings as binding_tests
import test_launcher as launcher


class DoctorTests(unittest.TestCase):
    owned_cleanup = launcher.LauncherTests.owned_cleanup
    setUp = launcher.LauncherTests.setUp
    stub = launcher.LauncherTests.stub
    tmux = launcher.LauncherTests.tmux
    run_script = launcher.LauncherTests.run_script
    generated = launcher.LauncherTests.generated
    load = launcher.LauncherTests.load
    attach = launcher.LauncherTests.attach
    wait_until = launcher.LauncherTests.wait_until
    bindings = binding_tests.BindingTests.bindings
    ownership = binding_tests.BindingTests.ownership

    def state(self):
        files = {path.relative_to(self.home): path.read_bytes()
                 for directory in [self.home / "cache", self.home / "config"]
                 if directory.exists() for path in directory.rglob("*") if path.is_file()}
        return self.bindings(), self.ownership(), files

    def test_default_diagnosis_does_not_create_a_shared_cache(self):
        self.tmux("set-option", "-gu", "@tmux-popups-profile")
        self.tmux("set-option", "-gu", "@tmux-popups-conflicts")
        self.tmux("set-option", "-gu", "@tmux-popups-availability")
        before = self.state()
        result = self.run_script("scripts/doctor.sh")
        self.assertIn("@tmux-popups-profile = small [default]", result.stdout)
        self.assertIn("@tmux-popups-conflicts = skip [default]", result.stdout)
        self.assertIn("default XDG path", result.stdout)
        self.assertIn("shared cache is absent", result.stdout)
        self.assertIn("failures: 0", result.stdout)
        self.assertEqual(self.state(), before)
        self.assertFalse(self.generated().exists())

    def test_overrides_unavailable_disabled_and_conflicting_bindings(self):
        self.tmux("set-option", "-g", "@tmux-popups-conflicts", "skip")
        registry = self.home / "doctor ' local.tsv"
        registry.write_text("fixture\tX\tx\tfixture\t70%\t70%\t-\tpopup\tforeground\ton\tmissing_doctor_tool\n")
        self.tmux("set-option", "-g", "@tmux-popups-local-registry", str(registry))
        self.tmux("set-option", "-g", "@tmux-popups-default-width", "65%")
        self.tmux("set-option", "-g", "@tmux-popups-fixture-enabled", "off")
        self.tmux("bind-key", "Enter", "display-message", "existing menu owner")
        self.load()
        self.tmux("set-option", "-g", "@tmux-popups-fixture-enabled", "on")
        before = self.state()
        result = self.run_script("scripts/doctor.sh")
        self.assertIn("65% [tmux option @tmux-popups-default-width]", result.stdout)
        self.assertIn("enabled=on [tmux option @tmux-popups-fixture-enabled]", result.stdout)
        self.assertIn("missing:missing_doctor_tool", result.stdout)
        self.assertIn(str(registry) + ":1", result.stdout)
        self.assertIn("existing menu owner", result.stderr)
        self.assertIn("cache differs", result.stdout)
        self.assertEqual(before, self.state())
        self.tmux("set-option", "-g", "@tmux-popups-fixture-enabled", "off")
        result = self.run_script("scripts/doctor.sh")
        self.assertIn("enabled=off [tmux option @tmux-popups-fixture-enabled]", result.stdout)

    def test_environment_registry_precedence_and_invalid_rows_are_read_only(self):
        registry = self.home / "environment.tsv"
        registry.write_text("fixture\tX\tx\tfrom environment\t70%\t70%\t-\n")
        self.load()
        before = self.state()
        result = self.run_script("scripts/doctor.sh", env=dict(self.env, TMUX_POPUPS_LOCAL_REGISTRY=str(registry)))
        self.assertIn("environment TMUX_POPUPS_LOCAL_REGISTRY", result.stdout)
        self.assertIn("from environment", result.stdout)
        self.assertEqual(before, self.state())
        registry.write_text("short\tinvalid\n")
        result = self.run_script("scripts/doctor.sh", check=False,
                                 env=dict(self.env, TMUX_POPUPS_LOCAL_REGISTRY=str(registry)))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(str(registry) + ":1", result.stderr)
        self.assertEqual(before, self.state())
        self.assertNotIn("tmux-popups-stage-", self.tmux("list-keys").stdout)

    def test_output_option_isolated_and_rejects_bad_arguments(self):
        self.load()
        before = self.state()
        output = self.base / "isolated ' output.conf"
        self.run_script("scripts/generate-config.sh", "--output", str(output))
        self.assertIn("# Generated by tmux-popups", output.read_text())
        self.assertEqual(before, self.state())
        for args in [("--bad",), ("--output",), ("--output", "")]:
            result = self.run_script("scripts/generate-config.sh", *args, check=False)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("usage:", result.stderr)
        self.assertEqual(before, self.state())

    def test_input_check_requires_terminal_and_bounded_seconds(self):
        for args in [("--input-check",), ("--input-check", "0"), ("--input-check", "31"),
                     ("--input-check", "invalid"), ("--input-check", "999999999999")]:
            result = self.run_script("scripts/doctor.sh", *args, check=False)
            self.assertNotEqual(result.returncode, 0)
        result = self.run_script("scripts/doctor.sh", "--help")
        self.assertIn("--input-check", result.stdout)

    def test_attached_input_check_receives_bytes_and_times_out(self):
        client = self.attach()
        target = self.tmux("list-clients", "-F", "#{client_name}").stdout.strip()
        def popup(seconds):
            process = subprocess.Popen([launcher.REAL_TMUX, "-S", str(self.socket),
                                        "display-popup", "-E", "-c", target, "-w", "95%", "-h", "70%",
                                        shlex.quote(str(launcher.ROOT / "scripts/doctor.sh")) + " --input-check " + seconds],
                                       env=self.env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            self.addCleanup(lambda: process.poll() is None and process.terminate())
            return process
        process = popup("5")
        self.wait_until(lambda: b"Type tmux-popups" in self.terminal_output)
        os.write(client, b"tmux-popups\r")
        process.wait(timeout=3)
        self.assertIn(b"74 6d 75 78 2d 70 6f 70 75 70 73", self.terminal_output)
        self.terminal_output.clear()
        process = popup("1")
        self.wait_until(lambda: b"Type tmux-popups" in self.terminal_output)
        process.wait(timeout=3)
        self.assertIn(b"No complete line", self.terminal_output)
