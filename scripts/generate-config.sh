#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$root/scripts/lib.sh"
registry="$root/popups.tsv"
cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/tmux-popups"
out="$cache_dir/generated.conf"
mkdir -p "$cache_dir"
# Each writer owns its file and validation tables. The last successful rename
# wins; readers see either complete version, never an in-progress write.
temporary="$(mktemp "$cache_dir/.generated.XXXXXXXX")"
table="tmux-popups-generate-${temporary##*/}"
cleanup() {
  local status=$?
  tmux unbind-key -a -T "$table" 2>/dev/null || true
  tmux unbind-key -a -T "$table-menu" 2>/dev/null || true
  rm -f "$temporary" "$temporary.stage" "$temporary.menu"
  return "$status"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

tmux_option() {
  local name="$1" fallback="$2" value
  value="$(tmux show-option -gqv "$name" 2>/dev/null || true)"
  printf '%s' "${value:-$fallback}"
}

menu_key="$(tmux_option @tmux-popups-menu-key Enter)"
reload_key="$(tmux_option @tmux-popups-reload-key R)"
default_width="$(tmux_option @tmux-popups-default-width 80%)"
default_height="$(tmux_option @tmux-popups-default-height 80%)"
vscode_command="$(tmux_option @tmux-popups-vscode-command 'code .')"
enable_vscode="$(tmux_option @tmux-popups-enable-vscode on)"
local_registry="$(resolve_local_registry)"
config_file="$(tmux_option @tmux-popups-config-file "$HOME/.tmux.conf")"
config_file="$(expand_home_path "$config_file")"

q() {
  local s="$1"
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//\$/\\\$}
  printf '%s' "$s"
}

shell_quote() {
  local value="$1"
  if [[ "$value" =~ ^[/a-zA-Z0-9_.-]+$ ]]; then
    printf '%s' "$value"
    return
  fi
  value=${value//\'/\'\\\'\'}
  printf "'%s'" "$value"
}

validate_literal() {
  case "$2" in
    *'#{'*|*'#('*|*$'\n'*|*$'\r'*) die "unsupported tmux format or line break in $1: $2" ;;
  esac
}
validate_literal 'plugin path' "$root"
validate_literal 'config path' "$config_file"
validate_literal 'registry path' "$local_registry"
valid_dimension "$default_width" && [[ "$default_width" != "-" ]] || die "invalid default width: $default_width"
valid_dimension "$default_height" && [[ "$default_height" != "-" ]] || die "invalid default height: $default_height"
validate_literal 'vscode command' "$vscode_command"
rows="$("$root/scripts/list-popups.sh" --tsv)"
while IFS=$'\t' read -r id direct_key row_menu_key title width height command launch_mode completion; do
  [[ "$id" =~ ^[a-zA-Z0-9_-]+$ ]] || die "unsupported popup id: $id"
  validate_literal "title for $id" "$title"
done <<<"$rows"

# Build a POSIX shell word at dispatch, after tmux has parsed the command.
# tmux q leaves tabs/newlines unquoted. Single quotes protect every path byte;
# s replaces each apostrophe with a close quote, quoted apostrophe, open quote.
# The substitution result is data, with no second format expansion or shell
# command substitution that could interpret hashes or strip trailing newlines.
shell_directory_format() {
  local prefix="$1" apostrophe="'\"'\"'"
  printf "'%s{s|'|%s|:pane_current_path}'" "$prefix" "$apostrophe"
}

popup_action() {
  local id="$1" menu="${2:-off}" cmd prefix="#" field
  [[ "$id" =~ ^[a-zA-Z0-9_-]+$ ]] || die "unsupported popup id: $id"
  # Menu parses its action once before run-shell expands formats. Defer the
  # snapshot so literal directory bytes never become shell source.
  [[ "$menu" == on ]] && prefix="##"
  cmd="$(shell_quote "$root/scripts/run-popup.sh") $id --launch"
  for field in client_name session_id window_id pane_id; do
    cmd+=" ${prefix}{q:${field}}"
  done
  cmd+=" $(shell_directory_format "$prefix")"
  printf 'run-shell "%s"' "$(q "$cmd")"
}

{
  printf '# Generated by tmux-popups. Do not edit.\n'
  printf '# Source: %s\n' "$registry"
  printf '# Local source: %s\n\n' "$local_registry"
  printf 'bind-key "%s" source-file "%s" \\; display-message "tmux config reloaded"\n\n' "$(q "$reload_key")" "$(q "$config_file")"

  printf '%s\n' "$rows" | while IFS=$'\t' read -r id direct_key row_menu_key title width height command launch_mode completion; do
    [[ -z "${id:-}" || "$id" == \#* ]] && continue
    [[ "$direct_key" == "-" ]] && continue
    printf 'bind-key "%s" %s\n' "$(q "$direct_key")" "$(popup_action "$id")"
  done

  printf '\nbind-key "%s" display-menu -T "#[align=centre] Quick Menu " -x C -y C' "$(q "$menu_key")"
  printf '%s\n' "$rows" | while IFS=$'\t' read -r id direct_key row_menu_key title width height command launch_mode completion; do
    [[ -z "${id:-}" || "$id" == \#* ]] && continue
    [[ "$row_menu_key" == "-" ]] && continue
    action="$(popup_action "$id" on)"
    printf ' "%s" "%s" "%s"' "$(q "$title")" "$(q "$row_menu_key")" "$(q "$action")"
  done

  if [[ "$enable_vscode" != "off" ]]; then
    # Defer the directory format past display-menu parsing. run-shell then
    # expands the single-quoted directory word once.
    vscode_action="run-shell \"cd -- $(q "$(shell_directory_format "##")") && $(q "$vscode_command")\""
    printf ' "vscode here" v "%s"' "$(q "$vscode_action")"
  fi
  reload_action="source-file \"$(q "$config_file")\"; display-message \"tmux config reloaded\""
  printf ' "reload tmux" R "%s"' "$(q "$reload_action")"
  printf ' "Exit" q ""\n'
} >"$temporary"

# Parse against the target server, then execute bindings only in private tables.
# Parsing alone does not check key names. Count canonical slots to catch aliases
# that refer to the same key without changing effective prefix bindings.
tmux source-file -n "$temporary"
expected=0
while IFS= read -r line; do
  [[ "$line" == 'bind-key "'* ]] || continue
  printf 'bind-key -T "%s" %s\n' "$table" "${line#bind-key }"
  ((expected+=1))
done <"$temporary" >"$temporary.stage"
tmux source-file "$temporary.stage"
actual="$(tmux list-keys -T "$table" | wc -l)"
[[ "$actual" -eq "$expected" ]] || die "duplicate direct shortcut after target tmux key normalization"
expected=2
{
  printf 'bind-key -T "%s" "R" display-message reload\n' "$table-menu"
  printf 'bind-key -T "%s" "q" display-message exit\n' "$table-menu"
  if [[ "$enable_vscode" != off ]]; then
    printf 'bind-key -T "%s" "v" display-message vscode\n' "$table-menu"
    ((expected+=1))
  fi
  while IFS=$'\t' read -r id direct_key row_menu_key title width height command launch_mode completion; do
    [[ -n "$id" && "$row_menu_key" != "-" ]] || continue
    printf 'bind-key -T "%s" "%s" display-message "%s"\n' "$table-menu" "$(q "$row_menu_key")" "$id"
    ((expected+=1))
  done <<<"$rows"
} >"$temporary.menu"
tmux source-file "$temporary.menu"
actual="$(tmux list-keys -T "$table-menu" | wc -l)"
[[ "$actual" -eq "$expected" ]] || die "duplicate menu shortcut after target tmux key normalization"
mv -f -- "$temporary" "$out"
